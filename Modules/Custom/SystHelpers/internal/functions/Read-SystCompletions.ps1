function Read-SystCompletions {
    <#
        .SYNOPSIS
        Registers PowerShell completions generated by the Syst CLI.

        .DESCRIPTION
        Executes completion code produced by the installed Syst executable.

        Only use this function with a trusted Syst installation.
        The generated completion code runs in the current PowerShell session.
    #>

    [System.Diagnostics.CodeAnalysis.SuppressMessageAttribute(
        'PSAvoidUsingInvokeExpression',
        '',
        Justification = (
            'Intentionally evaluates PowerShell completion code ' +
            'generated by the trusted local Syst executable.'
        )
    )]
    [CmdletBinding()]
    param()

    if (
        Get-Variable `
            -Name SystCompletionsLoaded `
            -Scope Script `
            -ValueOnly `
            -ErrorAction SilentlyContinue
    ) {
        return
    }

    if (Get-Command Complete-Syst -ErrorAction SilentlyContinue) {
        $script:SystCompletionsLoaded = $true
        return
    }

    $systCommand = Get-Command `
        -Name syst `
        -CommandType Application `
        -ErrorAction SilentlyContinue |
        Select-Object -First 1

    if (-not $systCommand) {
        Write-Verbose 'Syst executable not found; skipping completions.'
        return
    }

    try {
        $output = @(
            & $systCommand.Path completion powershell
        )

        $exitCode = $LASTEXITCODE

        if ($exitCode -ne 0) {
            throw "Syst completion generation returned exit code $exitCode."
        }

        $completions = $output -join [Environment]::NewLine

        if ([string]::IsNullOrWhiteSpace($completions)) {
            throw 'Syst returned no completion code.'
        }

        ## Validate syntax, not trustworthiness.
        $tokens = $null
        $parseErrors = $null

        $null = [Management.Automation.Language.Parser]::ParseInput(
            $completions,
            [ref] $tokens,
            [ref] $parseErrors
        )

        if (@($parseErrors).Count -gt 0) {
            throw 'Syst returned completion code containing syntax errors.'
        }

        if ($completions -notmatch 'Register-ArgumentCompleter|Complete-') {
            throw 'Syst output does not resemble the expected completion script.'
        }

        Invoke-Expression -Command $completions -ErrorAction Stop

        $script:SystCompletionsLoaded = $true

        Write-Verbose 'Syst completions loaded successfully.'
    }
    catch {
        Write-Warning (
            'Failed to load Syst completions: ' +
            $_.Exception.Message
        )
    }
}
